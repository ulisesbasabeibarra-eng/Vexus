// Constructor: inicialización correcta del objeto display
Oled::Oled() : display(128, 64, &Wire, -1) {}

void Oled::begin() {
  if(!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
    Serial.println(F("Fallo OLED"));
    for(;;);
  }

  // Imprime imagen de Vexus
  display.clearDisplay();
  display.drawBitmap(0, 0, vexusImagen, 128, 64, WHITE);
  display.display();
}

void Oled::mostrarMensaje(String texto) {
  display.clearDisplay();
  display.setCursor(10, 25);
  display.setTextSize(1);
  display.print(texto);
  display.display();
}