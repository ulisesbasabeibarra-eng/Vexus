void manejarMenuPrincipal(bool up, bool enter, bool down) {
  if (up) {
    menuIndex--;
    if (menuIndex < 0) menuIndex = num_items - 1;
  }
  if (down) {
    menuIndex++;
    if (menuIndex >= num_items) menuIndex = 0;
  }
  if (enter) {
    ejecutarAccionMenu();
  }
}

void ejecutarAccionMenu() {
  switch (menuIndex) {
    case 0: // Cronometro
      cronoActivo = true;
      tiempoInicio = millis();
      digitalWrite(led, LOW);
      estadoActual = cronometro;
      break;
    case 1: // Calibracion
      mostrarMensaje("Calibrando...");
      calibrar();
      mostrarMensaje("Calibracion OK");
      delay(1000);
      break;
    case 2: // Guardar Calibracion
      EEPROM.put(0, 123); 
      mostrarMensaje("Guardado EEPROM");
      delay(1500);
      break;
    case 3: // Cargar Calibracion
      int llave;
      EEPROM.get(0, llave);
      if (llave == 123) {
        mostrarMensaje("Datos Cargados!");
      } else {
        mostrarMensaje("No hay datos :(");
      }
      delay(1500);
      break;
    case 4: // Valores
      valorIndex = 0;
      estadoActual = val_select;
      break;
    case 5: // Extra
      estadoActual = EXTRA;
      break;
  }
}

